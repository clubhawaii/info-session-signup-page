// 지역 글자(「경기 용인시 처인구 …」, 「강원 속초」) → [위도, 경도]. 모르면 null
window.TRAVEL.geoOf = function (text) {
  var T = window.TRAVEL, w = String(text || "").trim().split(/\s+/);
  if (!w[0]) return null;
  var sido = T.SIDO[w[0]] || w[0].replace(/(특별자치시|특별자치도|특별시|광역시|도)$/, "");
  if (!T.GEO[sido]) return null;
  var city = (w[1] || "").replace(/(시|군)$/, "");
  return T.GEO[sido + " " + city] || T.GEO[sido];
};
// 예상 이동 시간(시간). 강연자 출발 지역이 여러 곳(쉼표)이면 가장 가까운 곳. 알 수 없으면 null
window.TRAVEL.hours = function (from, to) {
  var T = window.TRAVEL, b = T.geoOf(to);
  if (!b) return null;
  var best = null;
  String(from || "").split(/[,，\/]/).forEach(function (f) {
    var a = T.geoOf(f);
    if (!a) return;
    var r = Math.PI / 180, dLat = (b[0] - a[0]) * r, dLon = (b[1] - a[1]) * r;
    var h = Math.sin(dLat / 2) * Math.sin(dLat / 2) + Math.cos(a[0] * r) * Math.cos(b[0] * r) * Math.sin(dLon / 2) * Math.sin(dLon / 2);
    var km = 6371 * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
    var hours = T.BASE_HOURS + km / T.KM_PER_HOUR;
    if ((a[0] < 34 || b[0] < 34) && !(a[0] < 34 && b[0] < 34)) hours = Math.max(hours, 3);   // 제주 ↔ 육지
    if (best === null || hours < best) best = hours;
  });
  return best;
};
